#!/usr/bin/env python3
"""Developer tool: extracts level data, tile-type table and 8x8 font from the
Atari 8-bit "Shift" XEX (by Haplo) into source/atari_data.c.  usage: export.py shift.xex out.c"""
import sys
d = open(sys.argv[1], 'rb').read()
M = bytearray(65536)
i = 0
while i < len(d):
    if d[i:i+2] == b'\xff\xff': i += 2
    s = d[i] | d[i+1] << 8; e = d[i+2] | d[i+3] << 8; i += 4
    M[s:e+1] = d[i:i+e-s+1]; i += e-s+1
NL = 37
out = ['// GENERATED by tools/atari/export.py from the Atari 8-bit port of Shift.',
       '// Level layouts: Antony Lavelle (Armor Games) / Haplo. For personal use.',
       '#include "atari_data.h"', '']
rle_names = []
heads = []
objs_all = []
for lv in range(NL):
    p = M[0x7e80+lv] | M[0x7ea6+lv] << 8
    heads.append((M[p], M[p+1]))
    q = p + 4
    objs = []
    while M[q] != 0:
        objs.append((M[q], M[q+1], (M[q+2] | (M[q+3] + 0x20) << 8) - 0x2000))
        q += 4
    q += 1
    start = q
    cells = 0
    while True:
        v, c = M[q], M[q+1]
        if v == 0xff and c == 0xff: break
        cells += c; q += 2
    assert cells == 1000, (lv, cells)
    rle = bytes(M[start:q])
    out.append('static const unsigned char RLE%d[] = {%s};' % (lv, ','.join(str(b) for b in rle)))
    objs_all.append(objs)
out.append('')
out.append('const AtariLevel ATARI_LEVELS[ATARI_NUM_LEVELS] = {')
for lv in range(NL):
    ob = ','.join('{%d,%d,%d}' % o for o in objs_all[lv])
    out.append('  {%d,%d,%d,{%s},RLE%d,%d},' % (heads[lv][1], heads[lv][0], len(objs_all[lv]), ob or '{0,0,0}', lv, 0))
out.append('};')
out.append('')
out.append('const unsigned char ATARI_TYPES[256] = {' + ','.join(str(M[0x7f30+i]) for i in range(256)) + '};')
out.append('')
out.append('const unsigned char ATARI_FONT[128][8] = {')
for g in range(128):
    out.append('  {' + ','.join(str(M[0x2400+g*8+r]) for r in range(8)) + '},')
out.append('};')
out.append('')
out.append('const unsigned char ATARI_BUTTON[4][8] = {')
for f in range(4):
    out.append('  {' + ','.join(str(M[0x26b0+f*8+r]) for r in range(8)) + '},')
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('ok')
